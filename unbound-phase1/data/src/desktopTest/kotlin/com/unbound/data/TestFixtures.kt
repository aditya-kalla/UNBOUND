package com.unbound.data

import com.unbound.data.model.ParsedArtwork
import com.unbound.data.model.ParsedTrack

fun testTrack(
    title: String,
    artists: List<String> = listOf("Artist"),
    albumArtist: String? = artists.firstOrNull(),
    album: String? = "Album",
    genres: List<String> = emptyList(),
    trackNo: Int? = 1,
    discNo: Int? = 1,
    year: Int? = 2024,
    durationMs: Long = 180_000L,
    bitrateKbps: Int? = 320,
    sampleRate: Int? = 44100,
    channels: Int? = 2,
    bitDepth: Int? = 16,
    codec: String? = "mp3",
    isLossless: Boolean = false,
    rgTrackGainDb: Double? = null,
    rgTrackPeak: Double? = null,
    rgAlbumGainDb: Double? = null,
    rgAlbumPeak: Double? = null,
    hasEmbeddedLyrics: Boolean = false,
    artwork: ParsedArtwork? = null,
    fingerprint: String? = "fp-$title",
    metaVersion: Int = 1,
) = ParsedTrack(
    title = title,
    artists = artists,
    albumArtist = albumArtist,
    album = album,
    genres = genres,
    trackNo = trackNo,
    discNo = discNo,
    year = year,
    durationMs = durationMs,
    bitrateKbps = bitrateKbps,
    sampleRate = sampleRate,
    channels = channels,
    bitDepth = bitDepth,
    codec = codec,
    isLossless = isLossless,
    rgTrackGainDb = rgTrackGainDb,
    rgTrackPeak = rgTrackPeak,
    rgAlbumGainDb = rgAlbumGainDb,
    rgAlbumPeak = rgAlbumPeak,
    hasEmbeddedLyrics = hasEmbeddedLyrics,
    artwork = artwork,
    fingerprint = fingerprint,
    metaVersion = metaVersion,
)
